import { chromium } from 'playwright';
import { writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[], checks=[];
for(const width of [1440,390]){
 const page=await browser.newPage({viewport:{width,height:950}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/#top');
 await page.locator('#starterMount .cm-content').waitFor();
 await page.locator('.starter-run').click();
 await page.waitForFunction(()=>!document.querySelector('.starter-run').disabled);
 const output=await page.locator('.starter-output').innerText();
 if(!output.includes('100'))throw Error('starter run failed '+output);
 await page.locator('#starterMount .cm-content').fill((await page.locator('.starter-editor').inputValue()).replace('100','80'));
 await page.reload(); await page.locator('#starterMount .cm-content').waitFor();
 if(!(await page.locator('.starter-editor').inputValue()).includes('80'))throw Error('draft lost');
 await page.locator('#startButton').click();
 await page.locator('#incidentCard h2').waitFor();
 if(!await page.locator('#comicOpening').isVisible())throw Error('comic opener should be visible');
 if(await page.locator('#chatCard').isVisible())throw Error('remaining story should be optional');
 await page.locator('#compactToggle').click();
 if(!await page.locator('#incidentCard').isVisible())throw Error('focus hides task');
 await page.locator('#compactToggle').click();
 await page.locator('#nextButton').click();
 if(!page.url().endsWith('#chapter-2'))throw Error('route goes to supplement');
 await page.goto('http://127.0.0.1:4173/#supplement-go-real-test-file');
 await page.locator('[data-stage="practice"]').click();
 await page.locator('#completeButton').click();
 const read=await page.evaluate(()=>JSON.parse(localStorage.getItem('manga-go-read-supplements')||'[]'));
 if(!read.includes('supplement-go-real-test-file'))throw Error('reading record missing');
 await page.goto('http://127.0.0.1:4173/#chapter-1');
 await page.locator('[data-stage="read"]').click();
 if(!await page.locator('#codeCard .code-block').isVisible())throw Error('worked example hidden');
 await page.locator('[data-stage="practice"]').click();
 if(!await page.locator('#exerciseCard .cm-content').first().isVisible())throw Error('editor missing');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(overflow)throw Error('horizontal overflow '+width);
 await page.locator('[data-stage="understand"]').click();
 await page.evaluate(()=>{ document.documentElement.style.scrollBehavior='auto'; window.scrollTo(0,0); });
 await page.waitForTimeout(400);
 await page.screenshot({path:`evidence/learning-refactor-${width}.png`,fullPage:true});
 checks.push({width,starterRun:output,draft:true,route:true,optionalStory:true,focus:true,readingRecord:true,editor:true,overflow:false});
 await page.close();
}
await browser.close();
const hashes={};for(const file of ['interactive/app.js','interactive/styles.css','interactive/index.html','interactive/lesson-briefs.js','interactive/starter.js'])hashes[file]=createHash('sha256').update(await readFile(file)).digest('hex');
await writeFile('evidence/learning-refactor.json',JSON.stringify({time:new Date().toISOString(),hashes,checks,errors},null,2));
if(errors.length)throw Error(errors.join('\n'));
console.log(JSON.stringify({checks,errors}));
